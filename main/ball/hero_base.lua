-- Базовая модель героя: взаимодействие с миром КАК У МЯЧИКА (hero_ball — эталон).
--
-- Все герои (мячик, Slinky, Bumpy) наследуют этот контракт через метатаблицу и
-- переопределяют только визуальную часть. Физика взаимодействия с миром задана
-- ЗДЕСЬ и одинакова для всех:
--   * липкая (закрашенная) платформа — герой прилипает и ждёт команды игрока;
--   * приземление без команды — автоматический отскок на jump_speed;
--   * команда ввода принимается только в окне касания (герой не стоит на месте);
--   * повторные контакты Box2D на липкой поверхности игнорируются;
--   * высота подскока и длительность бокового шага — как у мячика.
--
-- Герой не может «разойтись» с эталоном в поведении: если он не переопределил
-- функцию, работает реализация мячика.
local M = {}

M.name = "hero"

-- липкая платформа: герой прилипает и за одно касание может совершить РОВНО
-- одно действие (высокий прыжок ИЛИ соскок в сторону) — как мячик
M.sticks_on_platform = true

-- высота подскока при шаге в сторону и при высоком прыжке — как у мячика
function M.hop_height(self)
    return self.env.hop_height
end

-- длительность бокового шага — как у мячика
function M.step_scale(self)
    return 1.0
end

-- приземление без команды игрока: автоматический отскок. Вызывается общим
-- кодом (settle_or_stick) на каждом приземлении, поэтому герой без своего
-- переопределения ведёт себя как мячик
function M.settle(self)
    go.set("#collision_object", "linear_velocity",
        vmath.vector3(0.0, self.env.jump_speed, 0.0))
    self.next_touch_time = self.time + self.env.period
end

-- команда принимается только в окне касания: герой не стоит на месте
function M.allow_from_rest(self)
    return false
end

-- на липкой поверхности Box2D повторяет контакты (герой не отрывается от
-- платформы) — их игнорируем, иначе каждый CONTACT_DEDUP запускал бы новое
-- приземление и новый отскок
function M.ignore_contacts(self)
    return self.sticky_rest == true
end

-- визуальные хуки: по умолчанию ничего не делают, герой переопределяет нужные
function M.setup(self, env)
    self.env = env
end

function M.activate(self) end

function M.deactivate(self) end

function M.reset(self) end

function M.update(self, dt) end

function M.apply_squash(self) end

function M.on_action(self, direction, duration) end

function M.on_ceiling(self) end

-- герой лёг на липкую платформу и ждёт команды (мячик просто лежит)
function M.on_rest(self) end

-- герой приземлился на платформу. drop — высота падения над поверхностью (px).
-- Физика приземления уже выполнена (M.settle), здесь только визуальная
-- реакция: клип приземления, сжатие пружины, глубокая посадка при большом
-- падении. Мячику дополнительная реакция не нужна — он сплющивается в update.
function M.on_land(self, drop) end

-- герой отскочил от обычной платформы (settle уже дал импульс): визуальная
-- реакция на отскок. Мячику не нужна — сплющивание идёт в update.
function M.on_bounce(self) end

-- принудительно поставить героя на ноги при приземлении на липкую платформу.
-- Для мячика понятия «ноги» нет, поэтому по умолчанию ничего не делает; герой
-- с анимацией ног (Bumpy) переопределяет
function M.force_feet_landing(self) end

return M
