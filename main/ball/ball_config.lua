-- Общая конфигурация мяча: сетка экрана, физика прыжка, тайминги ввода,
-- геометрия предметов и таблички EXIT, стартовые жизни, отсчёт ловушки.
--
-- Модуль не требует других модулей (лист дерева зависимостей): его читают
-- ball_grid, ball_world, ball_motion, ball_landing, ball_input, ball_goodies,
-- ball_progress и ball_trap. Все значения — константы игрового баланса,
-- менять их следует только здесь.
local C = {}

-- размер мяча и темп игрового цикла
C.SIZE = 32.0
C.BPM = 120.0

-- сетка игрового экрана 6 на 6
C.COLS = 6
C.ROWS = 6
C.SCREEN_W = 960.0
C.SCREEN_H = 640.0
C.CELL_W = C.SCREEN_W / C.COLS
C.CELL_H = C.SCREEN_H / C.COLS
C.RADIUS = C.SIZE / 2.0

-- предмет (goodies) — спрайт 32x32, как и мяч; сбор идёт только при касании
C.GOODIE_HALF = 16.0

-- табличка EXIT (текстура main/exit/exit.png): размеры в мировых пикселях,
-- см. spawn_exit в level.script. У таблички нет физического collision object,
-- чтобы она не блокировала траекторию мяча, поэтому контакт с ней проверяется
-- геометрически каждый кадр
C.EXIT_SIGN_HALF_W = 60.0
C.EXIT_SIGN_HALF_H = 40.0

-- число жизней на старте; теряется при контакте с шипами/горящей платформой
-- или при падении за пределы поля, HUD-карман рисует их сердечками
C.START_LIVES = 3

-- бесконечная ловушка: если наклонная платформа не даёт мячу выбраться
-- (наклон в сторону непробиваемой стены/края поля, в сторону разрушаемой стены
-- без ключа или к другой наклонной, направленной навстречу), показывается
-- плашка «YOU ARE TRAPPED» и ведётся обратный отсчёт до потери жизни
C.TRAP_COUNTDOWN = 3.0

-- высота платформы (одинаковая для всех уровней) и центр Y платформы нижнего ряда
C.PLATFORM_H = 20.0
C.PLATFORM_Y_BASE = 20.0
-- Y центра мяча в момент отскока от каждого ряда ячеек (индекс 0 — нижний ряд):
-- верхняя грань платформы + радиус мяча; рассчитывается от высоты платформы
C.BOUNCE_Y = {}
for c = 0, C.COLS - 1 do
    C.BOUNCE_Y[c] = C.PLATFORM_Y_BASE + C.PLATFORM_H / 2.0 + C.RADIUS + c * C.CELL_H
end

C.PERIOD = 60.0 / C.BPM
-- высота обычного прыжка: в верхней точке мяч не должен касаться платформы выше,
-- т.е. HEIGHT + 2*RADIUS < зазор между уровнями (48 + 32 < 106.7 - 20)
C.HEIGHT = 1.5 * C.SIZE
C.GRAVITY = 8.0 * C.HEIGHT / (C.PERIOD * C.PERIOD)
C.JUMP_SPEED = C.GRAVITY * C.PERIOD * 0.5
-- высокий прыжок (Space/Up): начальный импульс как при прыжке на один этаж;
-- первый уровень подъёма замедляется гравитацией, выше скорость становится
-- постоянной (JUMP_SPEED) — мяч летит до платформы сверху или верхнего края
-- игрового поля и может запрыгнуть на любой «этаж»
C.HIGH_JUMP_HEIGHT = C.CELL_H + C.HEIGHT
C.HIGH_JUMP_SPEED = math.sqrt(2.0 * C.GRAVITY * C.HIGH_JUMP_HEIGHT)

-- окно в мс до и после момента касания земли, в котором нажатие клавиши считается
C.THRESHOLD_MS = 100.0
C.THRESHOLD = C.THRESHOLD_MS / 1000.0

-- тач-управление (тачскрин). Жесты работают как удержание клавиш:
--   свайп вправо/влево с удержанием пальца — удержание «вправо»/«влево»
--   (мяч на каждом отскоке смещается в сторону, пока палец на экране);
--   свайп вверх с удержанием — удержание «высокий прыжок»;
--   короткий тап без движения — разовая команда по половине игрового поля.
-- Порог свайпа задаётся долей размера экрана, чтобы жест одинаково распознавался
-- на разных разрешениях устройств
C.SWIPE_MIN_FRAC = 0.05
-- «время жизни» разовой тап-команды: она принимается не мгновенно, а в окне
-- threshold вокруг следующего касания, поэтому держится чуть дольше одного
-- отскока (PERIOD = 0.5 с) и сбрасывается, как только действие выполнено
C.TOUCH_CMD_TIMEOUT = 0.7

-- сенсорное управление «тап по ячейке» (настройка bumpy.controls_mode = "cells"):
-- нажатие на игровую ячейку ставит намерение, которое выполняется, как только
-- мяч готов к действию (не в середине прыжка/отскока). Намерение живёт чуть
-- дольше одного цикла отскока, чтобы тап в полёте сработал при приземлении
C.CELL_CMD_TIMEOUT = 1.5

-- окно в с для дедупликации контактов между кадрами: пока мяч ещё не оторвался
-- от поверхности, Box2D присылает контакт повторно в следующем шаге физики
C.CONTACT_DEDUP = 0.1
-- короткое окно после начала действия (шаг/отскок/прыжок) в котором контакты
-- игнорируются: иначе «залипший» контакт того же кадра снова усаживает Slinky на
-- платформу и следующий кадр запускает ещё один шаг — прыжок через платформу
C.CONTACT_GUARD = 0.05

-- затухание «удара»: общая величина состояния self.squash, герои читают её в
-- своём update (мяч — сплющивание, Slinky — сжатие пружины)
C.SQUASH_DURATION = 0.15
-- величина сплющивания мяча; нужна также в геометрии удара о перегородку
C.SQUASH_AMOUNT = 0.25

-- толщина перегородки (совпадает с мешем и коллизией в wall.buffer/wall.collisionobject)
C.WALL_THICKNESS = 20.0

C.STEP = C.CELL_W
C.MOVE_DURATION = 0.25

-- «стена» (блок, кирпичная кладка): ширина в игровую ячейку (полуширина 70 —
-- не задевает границы, где могли бы стоять перегородки); по высоте кладка
-- занимает всю ячейку (level.script растягивает меш 140x100 на высоту ряда,
-- поэтому мировая высота блока равна CELL_H)
C.BLOCK_HALF_W = 70.0
C.BLOCK_HEIGHT = C.CELL_H

-- общие значения, которые нужны героям; передаются им в setup
C.ENV = {
    jump_speed = C.JUMP_SPEED,
    period = C.PERIOD,
    hop_height = C.HEIGHT,
    squash_amount = C.SQUASH_AMOUNT,
}

return C
