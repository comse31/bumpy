-- Геометрия HUD-полосы кармана, общая для отрисовки предметов
-- (main/pocket/pocket.script) и GUI-слоя сенсорного управления
-- (main/controls/controls.gui_script): круглая кнопка «назад» стоит ровно
-- слева от первой группы предметов, поэтому оба слоя считают координаты из
-- одних и тех же чисел и не могут разъехаться.
--
-- Координаты локальные: дизайнерская сетка полосы (x 0..960, y 640..720).
-- В мир они переводятся через main/render/camera_state (hud_x/hud_y/hud_scale).
local M = {}

M.MARGIN_X = 40.0   -- отступ от левого края экрана
M.STRIP_Y  = 680.0  -- вертикальный центр полосы (поле заканчивается на y = 640)

-- Круглая кнопка «назад»: вертикально по центру полосы, слева от предметов.
-- Диаметр 40 < высоты полосы (80), поэтому кнопка не выходит за её границы
-- и чуть крупнее собранных предметов (32 px, рисуются в масштабе 2/3).
M.BACK_SIZE = 40.0
-- Зазор между кнопкой и первой группой предметов: спрайт предмета шириной 32
-- рисуется в масштабе 2/3 (≈21), поэтому его левый край на ~10 px левее
-- центра. 22 px оставляют между кнопкой и первым предметом заметный просвет.
M.BACK_GAP  = 22.0
M.BACK_X    = M.MARGIN_X + M.BACK_SIZE * 0.5
M.ITEMS_X   = M.MARGIN_X + M.BACK_SIZE + M.BACK_GAP

return M
