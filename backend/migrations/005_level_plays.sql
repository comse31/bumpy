-- История выдачи сгенерированных уровней игроку (режим Adventure).
--
-- Требование игры: один и тот же уровень не должен предлагаться игроку, пока
-- он не сыграет все уровни из окна выдачи. Сервер запоминает, какие уровни уже
-- выдавались конкретному player_id (GET /api/levels/random?player_id=...), и
-- выбирает для него случайный уровень ТОЛЬКО из непросмотренных. Когда
-- непросмотренные заканчиваются, история игрока очищается — начинается новый
-- круг, и уровни снова доступны в случайном порядке.
--
-- player_id приходит с клиента (main/remote_db.lua). Он не является секретом и
-- нужен только для разделения истории: у каждого устройства свой круг. Если
-- player_id не передан, выдача остаётся прежней — чисто случайной.
--
-- FOREIGN KEY ... ON DELETE CASCADE: когда уровень удаляется (палец вниз или
-- очистка старых записей), история его выдач не остаётся «мусором» в таблице.

CREATE TABLE IF NOT EXISTS level_plays (
    -- Кто получил уровень (идентификатор устройства/игрока).
    player_id   TEXT NOT NULL,

    -- Какой уровень был выдан (ссылка на generated_levels).
    level_id    TEXT NOT NULL,

    -- Когда уровень был выдан (UTC, ISO-8601).
    played_at   TEXT NOT NULL,

    -- Один уровень — одна запись на игрока: повторная выдача обновляет время.
    PRIMARY KEY (player_id, level_id),

    FOREIGN KEY (level_id) REFERENCES generated_levels (level_id) ON DELETE CASCADE
);

-- Выборка истории конкретного игрока (исключение уже сыгранных уровней).
CREATE INDEX IF NOT EXISTS idx_level_plays_player
    ON level_plays (player_id);
